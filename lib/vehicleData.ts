// Générer les années (de l'année actuelle jusqu'à 30 ans en arrière)
export function getYears(): number[] {
  const currentYear = new Date().getFullYear() + 1; // Include next year for new models
  return Array.from({ length: 32 }, (_, i) => currentYear - i);
}
