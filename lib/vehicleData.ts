export function isPostalCodeServiced(postalCode: string): boolean {
  const normalized = postalCode.toUpperCase().replace(/\s/g, "");
  const prefix2 = normalized.substring(0, 2);
  const prefix3 = normalized.substring(0, 3);

  return serviceAreas.some(
    (area) =>
      area === prefix2 || area === prefix3 || normalized.startsWith(area)
  );
}

